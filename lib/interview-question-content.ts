const interviewerQuestionPrefix: Record<Locale, string> = canonicalLocaleRecord({
  'zh-HK': '面試官問：',
  'zh-TW': '面試官問：',
  'zh-Hans': '面试官问：',
  en: 'Interviewer asks:'
});

const halfRightAnswerPrefix: Record<Locale, string> = canonicalLocaleRecord({
  'zh-HK': '答啱一半嘅答案：',
  'zh-TW': '答對一半',
  'zh-Hans': '答对一半',
  en: 'Half-right answer:'
});

/**
 * Pull only the interviewer question from the opening blockquote.  In
 * particular, do not return the half-right answer that follows it: the live
 * rehearsal needs a question to ask, not a script to reveal.
 */
export function extractInterviewerQuestion(markdown: string, locale: Locale) {
  const prefix = interviewerQuestionPrefix[locale];
  const lines = markdown.split('\n');
  const firstLineIndex = lines.findIndex(line => line.startsWith(`> ${prefix}`));
  if (firstLineIndex === -1) return undefined;

  const questionLines = [lines[firstLineIndex].slice(`> ${prefix}`.length).trim()];
  for (let index = firstLineIndex + 1; index < lines.length; index += 1) {
    const line = lines[index];
    if (!line?.startsWith('>')) break;
    const content = line.replace(/^>\s?/, '').trim();
    if (!content) continue;
    if (content.startsWith(halfRightAnswerPrefix[locale])) break;
    questionLines.push(content);
  }

  const question = questionLines.join(' ').trim();
  return question.replace(/^["“]/, '').replace(/["”]$/, '').trim() || undefined;
}
